import type { NextConfig } from "next";

// The browser only talks to this Next.js server. Each backend endpoint has its own route handler
// in src/app/api/** (see src/lib/server/backend.ts); there is deliberately no catch-all rewrite.

const isDev = process.env.NODE_ENV === "development";

// Content Security Policy without nonces (see node_modules/next/dist/docs/01-app/02-guides/content-security-policy.md).
// Fonts are self-hosted by next/font and the API is same-origin, so 'self' covers everything.
const csp = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${isDev ? " 'unsafe-eval'" : ""}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' blob: data:",
  "font-src 'self'",
  "connect-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  ...(isDev ? [] : ["upgrade-insecure-requests"]),
].join("; ");

const securityHeaders = [
  { key: "Content-Security-Policy", value: csp },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), payment=()" },
  { key: "Cross-Origin-Opener-Policy", value: "same-origin" },
  // HTTPS only: browsers remember to never use plain http for this site (2 years).
  ...(isDev ? [] : [{ key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains; preload" }]),
];

const nextConfig: NextConfig = {
  poweredByHeader: false,
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
  cacheComponents: true,
  partialPrefetching: true,
  experimental: {
    // Every app page waits for the client-side login check (AuthProvider shows a spinner until then),
    // so no page can render on the server and the default validation logs "Could not validate that
    // a segment ... has instant navigation" for each one. Only validate segments that opt in with
    // `export const instant = true`.
    instantInsights: { validationLevel: "manual-warning" },
  },
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
};

export default nextConfig;
